// Helper to generate the SQL file and execute seed directly
async function run() {
  console.log('--- Starting New Products Seeding ---');
  console.log(`Total new products to seed: ${productsData.length}`);

  // Count total images referenced
  const allImages = productsData.flatMap(p => p.images);
  console.log(`Total images mapped across products: ${allImages.length}`);

  // Fetch categories, collections, and brands from DB
  const { data: categories } = await client.from('categories').select('id, slug');
  const { data: collections } = await client.from('collections').select('id, slug');
  const { data: brands } = await client.from('brands').select('id, slug');

  const catMap = Object.fromEntries(categories.map(c => [c.slug, c.id]));
  const colMap = Object.fromEntries(collections.map(c => [c.slug, c.id]));
  const brdMap = Object.fromEntries(brands.map(b => [b.slug, b.id]));

  // Build SQL script content
  let sql = `-- ==============================================================================
-- SEED NEW PRODUCTS INTO SUPABASE DATABASE
-- Mapped to corresponding Canadian collections, categories, and brands
-- Generated from /images/products/new-products/ directory (116 product images)
-- ==============================================================================

INSERT INTO public.products (
  slug, name, sku, category_id, brand_id, collection_id, price, original_price, currency, stock,
  is_featured, is_limited_edition, badge, rating, reviews_count, images, description, short_description,
  details, dimensions, material, made_in, created_by
) VALUES\n`;

  const rows = [];
  const dbUpsertPayload = [];

  for (const p of productsData) {
    const category_id = catMap[p.category_slug] || catMap['the-iconics'] || catMap['gifts'];
    const collection_id = colMap[p.collection_slug] || colMap['signature'];
    const brand_id = brdMap[p.brand_slug] || brdMap['memoriq'];

    const detailsJson = JSON.stringify(p.details).replace(/'/g, "''");
    const imagesArraySql = `ARRAY[${p.images.map(img => `'${img}'`).join(', ')}]`;
    const origPriceSql = p.original_price ? p.original_price.toFixed(2) : 'NULL';

    rows.push(`  (
    '${p.slug}',
    '${p.name.replace(/'/g, "''")}',
    '${p.sku}',
    (SELECT id FROM public.categories WHERE slug = '${p.category_slug}'),
    (SELECT id FROM public.brands WHERE slug = '${p.brand_slug}'),
    (SELECT id FROM public.collections WHERE slug = '${p.collection_slug}'),
    ${p.price.toFixed(2)}, ${origPriceSql}, '${p.currency}', ${p.stock},
    ${p.is_featured}, ${p.is_limited_edition}, '${p.badge.replace(/'/g, "''")}', ${p.rating.toFixed(1)}, ${p.reviews_count},
    ${imagesArraySql},
    '${p.description.replace(/'/g, "''")}',
    '${p.short_description.replace(/'/g, "''")}',
    '${detailsJson}'::jsonb,
    '${p.dimensions.replace(/'/g, "''")}', '${p.material.replace(/'/g, "''")}', '${p.made_in}',
    '00000000-0000-0000-0000-000000000001'::uuid
  )`);

    dbUpsertPayload.push({
      slug: p.slug,
      name: p.name,
      sku: p.sku,
      category_id: category_id,
      brand_id: brand_id,
      collection_id: collection_id,
      price: p.price,
      original_price: p.original_price,
      currency: p.currency,
      stock: p.stock,
      is_featured: p.is_featured,
      is_limited_edition: p.is_limited_edition,
      badge: p.badge,
      rating: p.rating,
      reviews_count: p.reviews_count,
      images: p.images,
      description: p.description,
      short_description: p.short_description,
      details: p.details,
      dimensions: p.dimensions,
      material: p.material,
      made_in: p.made_in,
      created_by: '00000000-0000-0000-0000-000000000001'
    });
  }

  sql += rows.join(',\n');
  sql += `\nON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  sku = EXCLUDED.sku,
  category_id = EXCLUDED.category_id,
  brand_id = EXCLUDED.brand_id,
  collection_id = EXCLUDED.collection_id,
  price = EXCLUDED.price,
  original_price = EXCLUDED.original_price,
  images = EXCLUDED.images,
  description = EXCLUDED.description,
  short_description = EXCLUDED.short_description,
  details = EXCLUDED.details,
  dimensions = EXCLUDED.dimensions,
  material = EXCLUDED.material,
  stock = EXCLUDED.stock,
  is_featured = EXCLUDED.is_featured,
  is_limited_edition = EXCLUDED.is_limited_edition,
  badge = EXCLUDED.badge,
  rating = EXCLUDED.rating,
  reviews_count = EXCLUDED.reviews_count,
  created_by = EXCLUDED.created_by,
  updated_at = NOW();\n`;

  // Write SQL file
  const sqlPath = path.join(__dirname, '../supabase/seed_new_products.sql');
  fs.writeFileSync(sqlPath, sql, 'utf-8');
  console.log(`Successfully generated SQL seed file: ${sqlPath}`);

  // Perform direct Upsert to Supabase
  console.log('Executing direct upsert to Supabase database...');
  const { data: upsertData, error: upsertError } = await client
    .from('products')
    .upsert(dbUpsertPayload, { onConflict: 'slug' });

  if (upsertError) {
    console.error('Error upserting to Supabase:', upsertError);
    process.exit(1);
  } else {
    console.log(`Successfully upserted ${dbUpsertPayload.length} products to Supabase!`);
  }

  // Verify total products count now
  const { count: finalCount } = await client.from('products').select('*', { count: 'exact', head: true });
  console.log(`Current total products in database: ${finalCount}`);

  // Summary by collection
  const { data: allProds } = await client.from('products').select('name, collection_id, collections(slug, name)');
  const colCounts = {};
  for (const pr of (allProds || [])) {
    const colName = pr.collections?.name || 'Unassigned';
    colCounts[colName] = (colCounts[colName] || 0) + 1;
  }
  console.log('Product distribution across collections:', colCounts);
}

run().catch(err => {
  console.error('Execution error:', err);
  process.exit(1);
});
